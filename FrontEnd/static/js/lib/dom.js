const SOLID = new Set(["play", "next", "end", "start", "spark"]);

/** Trusted, static SVG markup for an icon name. */
export function iconSvg(name, extraClass = "") {
  const cls = `icon${SOLID.has(name) ? " is-solid" : ""}${extraClass ? ` ${extraClass}` : ""}`;
  return `<svg class="${cls}" viewBox="0 0 24 24" aria-hidden="true">${PATHS[name] ?? ""}</svg>`;
}

export function icon(name, extraClass = "") {
  const wrap = document.createElement("template");
  wrap.innerHTML = iconSvg(name, extraClass);
  return wrap.content.firstChild;
}

/** Position of `el` relative to `host`. */
export function rectIn(el, host) {
  const a = el.getBoundingClientRect();
  const b = host.getBoundingClientRect();
  return { x: a.left - b.left, y: a.top - b.top, w: a.width, h: a.height };
}

